package heapranges

import "syscall"

var reserved []byte

func reserve() bool {
	var err error
	reserved, err = syscall.Mmap(-1, 0, 1<<20, syscall.PROT_READ|syscall.PROT_WRITE, syscall.MAP_ANON|syscall.MAP_PRIVATE)
	return err == nil
}
