# Runs the unit tests of this module that need compile-time instrumentation,
# built with otelc. This is the otelc counterpart of
# "go tool orchestrion go test ./...". All arguments go to "go test" (for
# example: scripts/otelc-test.sh -shuffle=on -count=1).
#
# A plain "go tool otelc go test ./..." does not work in this module:
#
#  1. otelc loads the rules of the packages that the tool file imports. The
#     tool file of this module (otel.instrumentation.go) is for applications,
#     and it does not import the detection packages (iast/...). This script
#     gives all the rule files to otelc with OTELC_RULES. With OTELC_RULES,
#     otelc does not read the tool files, so the list must also contain the
#     dd-trace-go rules that the tests need (tracer GLS and AppSec GLS).
#  2. otelc adds a file (otelc.runtime.go) to each package of the command line.
#     This file imports all the packages that the rules refer to. Many of them
#     import other packages of this module, so a run with several packages
#     makes import cycles. This script runs "go test" one time for each package.
#
# The script tests only the packages whose tests import
# github.com/DataDog/dd-iast-go/internal/build: these are the tests that need
# instrumentation (they call build.Instrumented()). The other tests do not
# change with otelc, and "go test ./..." already runs them.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

readonly module="github.com/DataDog/dd-iast-go"
readonly build_pkg="${module}/internal/build"

# The rule files of this module. "go list ./..." does not include the separate
# modules (_integration/..., benchmarks/...).
rules=()
while IFS= read -r dir; do
  for file in "${dir}"/otelc.yml "${dir}"/otelc.yaml "${dir}"/*.otelc.yml "${dir}"/*.otelc.yaml; do
    if [[ -f "${file}" ]]; then
      rules+=("${file}")
    fi
  done
done < <(go list -f '{{.Dir}}' ./...)

# Fail if the rules of this module are not found: without them, the tests that
# need instrumentation skip, and the run passes but tests nothing.
if [[ ${#rules[@]} -eq 0 ]]; then
  echo "otelc-test: no otelc rule file found in this module" >&2
  exit 1
fi
if [[ ! " ${rules[*]} " == *"/internal/build/otelc.yml "* ]]; then
  echo "otelc-test: internal/build/otelc.yml not found: the build is not marked as instrumented" >&2
  exit 1
fi

# The dd-trace-go rules, from the version in go.mod.
ddtrace_dir="$(go list -m -f '{{.Dir}}' github.com/DataDog/dd-trace-go/v2)"
rules+=(
  "${ddtrace_dir}/ddtrace/tracer/otelc.yaml"
  "${ddtrace_dir}/instrumentation/appsec/dyngo/gls.otelc.yaml"
)
for file in "${rules[@]}"; do
  if [[ ! -f "${file}" ]]; then
    echo "otelc-test: rule file not found: ${file}" >&2
    exit 1
  fi
done

# The packages whose tests need instrumentation.
packages=()
while IFS= read -r pkg; do
  if [[ -n "${pkg}" ]]; then
    packages+=("${pkg}")
  fi
done < <(go list \
  -f '{{$p := .ImportPath}}{{range .TestImports}}{{if eq . "'"${build_pkg}"'"}}{{$p}}{{"\n"}}{{end}}{{end}}{{range .XTestImports}}{{if eq . "'"${build_pkg}"'"}}{{$p}}{{"\n"}}{{end}}{{end}}' \
  ./... | sort -u)
if [[ ${#packages[@]} -eq 0 ]]; then
  echo "otelc-test: no package to test" >&2
  exit 1
fi
# The tests of internal/build check that the build tool is the expected one
# (see DD_IAST_EXPECTED_BUILD_TOOL below). They must always run.
if [[ ! " ${packages[*]} " == *" ${build_pkg} "* ]]; then
  echo "otelc-test: ${build_pkg} is not in the packages to test" >&2
  exit 1
fi

# otelc does not always remove the otelc.runtime.go file that it adds to a
# package of the command line (seen with otelc v1.2.1-0.20261017145842). A file
# that stays makes import cycles in the next run, and it also breaks the builds
# without otelc. Remove the files that otelc made (they start with its
# "generated" header) before each run and when the script stops.
package_dirs=()
while IFS= read -r dir; do
  package_dirs+=("${dir}")
done < <(go list -f '{{.Dir}}' ./...)

remove_runtime_files() {
  local dir file
  for dir in "${package_dirs[@]}"; do
    file="${dir}/otelc.runtime.go"
    if [[ -f "${file}" ]] && head -n 1 "${file}" | grep -q 'generated by the opentelemetry-go-compile-instrumentation tool'; then
      rm -f "${file}"
    fi
  done
}
trap remove_runtime_files EXIT

# otelc and Orchestrion must not share a build cache: when they do, a later
# Orchestrion build can fail at link time ("fingerprint mismatch"). Use a
# separate cache for otelc, unless OTELC_TEST_GOCACHE gives one (an absolute
# path). When GOCACHE is "off", start from the default cache location: otelc
# needs a build cache.
if [[ -z "${OTELC_TEST_GOCACHE:-}" ]]; then
  base_cache="$(go env GOCACHE)"
  if [[ "${base_cache}" == "off" ]]; then
    base_cache="$(GOCACHE= go env GOCACHE)"
  fi
  OTELC_TEST_GOCACHE="${base_cache}-otelc"
fi
GOCACHE="${OTELC_TEST_GOCACHE}"
export GOCACHE

OTELC_RULES="$(IFS=,; echo "${rules[*]}")"
export OTELC_RULES
# The tests of internal/build fail if the binary was not built with otelc.
export DD_IAST_EXPECTED_BUILD_TOOL=otelc

status=0
# The package is the first argument of "go test": all the arguments after a
# "-args" argument go to the test binary.
for pkg in "${packages[@]}"; do
  remove_runtime_files
  echo "otelc-test: ${pkg}"
  if ! go tool otelc go test "${pkg}" "$@"; then
    status=1
  fi
done
exit "${status}"
